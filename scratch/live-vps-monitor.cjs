const { chromium, expect } = require('@playwright/test');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const account = JSON.parse(execFileSync('ssh', ['-o', 'BatchMode=yes', 'vps-cong', 'sudo', '-n', 'python3', '/home/ubuntu/read-ui-accounts.py'], { encoding: 'utf8' })).platform;
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', () => errors.push('runtime error'));
  fs.mkdirSync(path.join(__dirname, 'ui-review'), { recursive: true });
  let loggedIn = false;
  try {
    await page.goto('https://sentinellan.149.118.50.176.sslip.io/platform/login');
    await page.locator('input[name="email"]').fill(account.email);
    await page.locator('input[name="password"]').fill(account.password);
    await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
    await page.waitForURL(url => !url.pathname.endsWith('/login'));
    loggedIn = true;
    const snapshotResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/platform/host/status') && r.request().method() === 'GET');
    await page.getByRole('button', { name: 'Máy chủ', exact: true }).click();
    const response = await snapshotResponse;
    expect(response.status()).toBe(200);
    const status = await response.json();
    expect(status.available).toBe(true); expect(status.stale).toBe(false);
    const monitor = page.locator('.host-monitor');
    await expect(monitor.getByRole('heading', { name: 'vps-cong', exact: true })).toBeVisible();
    const rows = monitor.locator('.host-docker-table tbody tr');
    await expect(rows).toHaveCount(status.snapshot.runtime.containers.length);
    const apiRow = rows.filter({ has: page.getByText('sentinellan-prod-api-1', { exact: true }) });
    await expect(apiRow.getByText('8443/TCP', { exact: true })).toBeVisible();
    await expect(apiRow.getByText('8080/TCP', { exact: true })).not.toBeVisible();
    await expect(monitor.getByText('9000/TCP', { exact: true }).first()).toBeVisible();
    await expect(monitor.getByText('127.0.0.1:3180 → 8443/TCP', { exact: true })).toBeVisible();
    await monitor.getByLabel('Tìm Docker').fill('sentinellan-prod-api-1');
    await expect(rows).toHaveCount(1);
    await monitor.getByLabel('Tìm Docker').fill('unmatched-docker-fixture');
    await expect(monitor.getByText('Không có Docker phù hợp bộ lọc.', { exact: true })).toBeVisible();
    await monitor.getByLabel('Tìm Docker').fill('');
    const refresh = page.waitForResponse(r => r.url().endsWith('/api/v1/platform/host/status'));
    await monitor.getByRole('button', { name: 'Kiểm tra VPS', exact: true }).click();
    expect((await refresh).status()).toBe(200);
    await page.screenshot({ path: path.join(__dirname, 'ui-review/live-vps-monitor-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await expect(monitor.getByRole('heading', { name: 'vps-cong', exact: true })).toBeVisible();
    await page.screenshot({ path: path.join(__dirname, 'ui-review/live-vps-monitor-mobile.png'), fullPage: true });
    const mobilePort = await apiRow.getByText('8443/TCP', { exact: true }).boundingBox();
    expect(mobilePort.x).toBeGreaterThanOrEqual(0);
    expect(mobilePort.x + mobilePort.width).toBeLessThanOrEqual(390);
    await apiRow.scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(__dirname, 'ui-review/live-vps-monitor-mobile-details.png') });
    const stale = { ...status, stale: true, message: 'Dữ liệu chưa được cập nhật.', snapshot: { ...status.snapshot, capturedAtUtc: new Date(Date.now() - 300000).toISOString() } };
    await page.route('**/api/v1/platform/host/status', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(stale) }));
    await monitor.getByRole('button', { name: 'Kiểm tra VPS', exact: true }).click();
    await expect(monitor.getByText('Chưa có dữ liệu mới', { exact: true })).toBeVisible();
    await page.unroute('**/api/v1/platform/host/status');
    await page.route('**/api/v1/platform/host/status', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Tạm thời chưa đọc được VPS.' }) }));
    await monitor.getByRole('button', { name: 'Kiểm tra VPS', exact: true }).click();
    await expect(monitor.getByRole('alert')).toContainText('Tạm thời chưa đọc được VPS.');
    await expect(rows).toHaveCount(status.snapshot.runtime.containers.length);
    await page.unroute('**/api/v1/platform/host/status');
    expect(errors).toEqual([]);
    console.log('PASS production Super Admin: automatic VPS, Docker list, actual and published ports, filters, refresh, stale warning, desktop and mobile');
  } finally {
    if (loggedIn) await page.evaluate(async () => { await fetch('/api/v1/platform/auth/logout', { method: 'POST', credentials: 'include', headers: { 'Content-Type': 'application/json', 'X-SentinelLAN-CSRF': '1' }, body: '{}' }); }).catch(() => {});
    await browser.close();
  }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
